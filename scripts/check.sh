#!/usr/bin/env sh
set -eu
. "$(dirname -- "$0")/common.sh"
cd_to_repo
. "$repo_root/scripts/packages.sh"

printf "Tracked-but-should-be-ignored (regression check):\n"
leaked=$(git ls-files -i --exclude-standard --cached || true)
if [ -n "$leaked" ]; then
    printf '%s\n' "$leaked" >&2
    printf 'FAIL: files above are tracked but would be ignored by .gitignore.\n' >&2
    printf 'This usually means .gitignore was tightened without untracking them.\n' >&2
    exit 1
fi
printf '  (none)\n'

printf "\nBroken symlinks in repo:\n"
find . -xtype l -print

printf "\nRoot dotfiles (local overrides):\n"
for root_link in $LOCAL_ROOT_DOTFILES; do
    if [ -e "$HOME/$root_link" ]; then
        printf "OK: %s\n" "$root_link"
    else
        printf "MISSING: %s\n" "$root_link"
    fi
done

printf "\nStow simulate: local common\n"
simulate_stow $LOCAL_COMMON

printf "\nStow simulate: arch-schlaeptop\n"
desktop_packages="$LOCAL_COMMON $LOCAL_HOST"
[ -d private ] && desktop_packages="$desktop_packages private"
simulate_stow $desktop_packages

printf "\nPackage tree:\n"
package_dirs="$LOCAL_COMMON $LOCAL_HOST"
if [ -d private ]; then
    package_dirs="$package_dirs private"
fi
find $package_dirs -maxdepth 4 -print | sort

printf "\nStale ignored files in working tree (OBS logs, caches, etc.):\n"
# Mirror the glob set from .gitignore that corresponds to app-generated junk.
# These are safe to remove; they are regenerated by their owning tools.
stale=$(find \
    media/.config/obs-studio/logs \
    media/.config/obs-studio/profiler_data \
    media/.config/obs-studio/crashes \
    media/.config/obs-studio/plugin_config \
    media/.config/obs-studio/plugin_manager \
    -mindepth 0 -maxdepth 0 2>/dev/null || true)
if [ -n "$stale" ]; then
    printf '%s\n' "$stale"
    printf '  (run `rm -rf` on the above to clean; they are gitignored and will be regenerated)\n'
else
    printf '  (none)\n'
fi

printf "\nGit status:\n"
git status --short --untracked-files=all
